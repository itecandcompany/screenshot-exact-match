import { useEffect, useState } from "react";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { Mail, Sparkles } from "lucide-react";
import { quoteSchema, type QuoteInput } from "@/content/quote";
import { services } from "@/content/services";
import { site } from "@/content/site";
import { Button } from "@/components/ui/button";

type StoredAudit = {
  brandUrl?: string;
  sourceTitle?: string;
  audit?: {
    brandName?: string;
    summary?: string;
    audience?: string;
    positioning?: string;
    score?: number;
    scores?: { label: string; score: number; note: string }[];
    opportunities?: string[];
    videoScripts?: { title: string; duration: string; hook: string; caption: string }[];
    staticAds?: { headline: string; subheadline: string; cta: string }[];
  };
};

function formatAuditReport(data: StoredAudit) {
  const audit = data.audit;
  if (!audit) return "";
  return [
    "AI BRAND AUDIT — GENERATED BY NEXTDOOR ADS",
    `Website/profile: ${data.brandUrl || "Not supplied"}`,
    `Page title: ${data.sourceTitle || "Not available"}`,
    `Brand: ${audit.brandName || "Not identified"}`,
    `Directional score: ${audit.score ?? "Not available"}/100`,
    "",
    "SUMMARY",
    audit.summary || "",
    "",
    `LIKELY AUDIENCE: ${audit.audience || "Not available"}`,
    `POSITIONING: ${audit.positioning || "Not available"}`,
    "",
    "CREATIVE SCORECARD",
    ...(audit.scores || []).map((item) => `- ${item.label}: ${item.score}/100 — ${item.note}`),
    "",
    "OPPORTUNITIES",
    ...(audit.opportunities || []).map((item, index) => `${index + 1}. ${item}`),
    "",
    "VIDEO CONCEPTS",
    ...(audit.videoScripts || []).map((item, index) => `${index + 1}. ${item.title} (${item.duration}) — Hook: ${item.hook}. Caption: ${item.caption}`),
    "",
    "STATIC AD CONCEPTS",
    ...(audit.staticAds || []).map((item, index) => `${index + 1}. ${item.headline} — ${item.subheadline} — CTA: ${item.cta}`),
    "",
    "Note: AI-generated directional review based on publicly accessible page content. Human review required; this is not measured campaign performance.",
  ].join("\n");
}

export function QuoteForm({
  service,
  packageName,
}: {
  service?: string | undefined;
  packageName?: string | undefined;
}) {
  const [auditReport, setAuditReport] = useState("");
  const [auditBrandUrl, setAuditBrandUrl] = useState("");
  const [emailError, setEmailError] = useState("");
  const [emailSent, setEmailSent] = useState(false);
  const {
    register,
    handleSubmit,
    formState: { errors, isSubmitting },
  } = useForm<QuoteInput>({
    resolver: zodResolver(quoteSchema),
    defaultValues: {
      service: service || "",
      budget: "discuss",
      contact: "email",
      website: "",
      description: packageName ? `I am interested in the ${packageName} monthly package. ` : "",
    },
  });

  useEffect(() => {
    try {
      const raw = sessionStorage.getItem("nextdoor-brand-audit-intake");
      if (!raw) return;
      const saved = JSON.parse(raw) as StoredAudit;
      setAuditReport(formatAuditReport(saved));
      setAuditBrandUrl(saved.brandUrl || "");
    } catch {
      setEmailError("The saved brand audit could not be read. You can still submit your project details.");
    }
  }, []);

  async function submitEnquiry(data: QuoteInput) {
    setEmailError("");
    setEmailSent(false);
    try {
      const response = await fetch("/api/quote", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ ...data, auditReport }),
      });
      const result = await response.json().catch(() => ({}));
      if (!response.ok || !result.success) {
        throw new Error(typeof result.error === "string" ? result.error : "We could not send your enquiry. Please try again.");
      }
      setEmailSent(true);
    } catch (error) {
      setEmailError(error instanceof Error ? error.message : "We could not send your enquiry. Please try again.");
    }
  }

  return (
    <form
      noValidate
      onSubmit={handleSubmit(submitEnquiry)}
      className="grid sm:grid-cols-2 gap-6"
    >
      {auditReport && (
        <div className="sm:col-span-2 rounded-sm border border-primary/30 bg-secondary p-5">
          <div className="flex items-center gap-2 text-sm font-bold">
            <Sparkles size={17} /> AI brand audit attached
          </div>
          <p className="text-xs text-muted-foreground mt-2">
            {auditBrandUrl} — the audit summary, scorecard, opportunities and creative concepts
            will be included with your project enquiry.
          </p>
          <details className="mt-3">
            <summary className="cursor-pointer text-xs font-semibold">Preview attached audit report</summary>
            <pre className="mt-3 whitespace-pre-wrap break-words text-xs leading-6">{auditReport}</pre>
          </details>
        </div>
      )}
      {[
        { key: "name", label: "Full name", type: "text", placeholder: "Your full name" },
        { key: "business", label: "Business / organisation", type: "text", placeholder: "Your business name" },
        { key: "email", label: "Email address", type: "email", placeholder: "you@yourbusiness.com" },
        { key: "phone", label: "Phone / WhatsApp", type: "tel", placeholder: "+255 …" },
      ].map((f) => (
        <div className="quote-field" key={f.key}>
          <label htmlFor={f.key}>{f.label}</label>
          <input
            id={f.key}
            type={f.type}
            placeholder={f.placeholder}
            maxLength={f.key === "email" ? 255 : 100}
            {...register(f.key as "name" | "business" | "email" | "phone")}
            aria-invalid={!!errors[f.key as keyof QuoteInput]}
            aria-describedby={`${f.key}-error`}
          />
          <span id={`${f.key}-error`} className="field-error">
            {errors[f.key as keyof QuoteInput]?.message}
          </span>
        </div>
      ))}
      <div className="quote-field">
        <label htmlFor="service">Service required</label>
        <select id="service" {...register("service")} aria-invalid={!!errors.service}>
          <option value="">Select a service</option>
          {services.map((s) => <option key={s.slug} value={s.slug}>{s.title}</option>)}
        </select>
        {errors.service && <span className="field-error">{errors.service.message}</span>}
      </div>
      <div className="quote-field">
        <label htmlFor="budget">Budget range</label>
        <select id="budget" {...register("budget")}>
          <option value="discuss">Let’s discuss</option>
          <option value="under-100000">Under TSh 100,000</option>
          <option value="100000-300000">TSh 100,000 – 300,000</option>
          <option value="300000-500000">TSh 300,000 – 500,000</option>
          <option value="500000-plus">TSh 500,000+</option>
        </select>
      </div>
      <div className="quote-field sm:col-span-2">
        <label htmlFor="description">Tell us about your project</label>
        <textarea
          id="description"
          rows={5}
          maxLength={3000}
          placeholder="Your goals, ideas and what you have in mind…"
          {...register("description")}
          aria-invalid={!!errors.description}
        />
        {errors.description && <span className="field-error">{errors.description.message}</span>}
      </div>
      <div className="quote-field">
        <label htmlFor="contact">Preferred contact method</label>
        <select id="contact" {...register("contact")}>
          <option value="email">Email</option>
          <option value="phone">Phone call</option>
          <option value="whatsapp">WhatsApp</option>
        </select>
      </div>
      <div className="hidden" aria-hidden="true">
        <label htmlFor="website">Website</label>
        <input id="website" tabIndex={-1} autoComplete="off" {...register("website")} />
      </div>
      <p className="sm:col-span-2 text-xs text-muted-foreground leading-6">
        Your enquiry is sent securely to NEXTDOOR ADS. If you include an AI brand audit, its summary
        and recommendations are attached to the enquiry. You can also reach us at {site.email}.
      </p>
      <div className="sm:col-span-2">
        <Button type="submit" variant="forest" disabled={isSubmitting}>
          <Mail /> {isSubmitting ? "Sending enquiry…" : "Send project enquiry"}
        </Button>
        {emailError && <p role="alert" className="field-error mt-3">{emailError}</p>}
        {emailSent && (
          <div role="status" className="mt-4 rounded-sm border border-primary/30 bg-secondary p-4">
            <p className="text-sm font-semibold">Your enquiry has been sent successfully.</p>
            <p className="text-xs text-muted-foreground mt-2">Thank you for contacting NEXTDOOR ADS. We’ll follow up using your preferred contact method.</p>
          </div>
        )}
      </div>
    </form>
  );
}
